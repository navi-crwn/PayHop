import { defineConfig, type Plugin } from 'vite';
import { svelte } from '@sveltejs/vite-plugin-svelte';
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

/* Writes dist/sw.js after the build: precache every built file (so the generator and the split
   calculator work offline once the page has loaded), cache-first for the app's own files, and the
   shell for navigations. Never touches /api, /auth or /hop. */
function offline(): Plugin {
  return {
    name: 'payhop-sw',
    apply: 'build',
    closeBundle() {
      const dist = join(process.cwd(), 'dist');
      const files: string[] = [];
      const walk = (d: string) => {
        for (const n of readdirSync(d)) {
          const p = join(d, n);
          if (statSync(p).isDirectory()) walk(p);
          else if (n !== 'sw.js' && !n.endsWith('.map') && !n.startsWith('LICENSE')) files.push('/' + relative(dist, p).split(sep).join('/'));
        }
      };
      walk(dist);
      files.sort();
      const h = createHash('sha256');
      for (const f of files) h.update(f).update(readFileSync(join(dist, f)));
      const version = h.digest('hex').slice(0, 12);
      const list = ['/', ...files.filter((f) => f !== '/index.html')];
      writeFileSync(join(dist, 'sw.js'), `/* generated by vite.config.ts */
const CACHE = 'payhop-${version}';
const FILES = ${JSON.stringify(list)};
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k.startsWith('payhop-') && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', (e) => {
  const req = e.request;
  const url = new URL(req.url);
  if (req.method !== 'GET' || url.origin !== location.origin || /^\/(api|auth|hop)\//.test(url.pathname)) return;
  if (req.mode === 'navigate') {
    e.respondWith(fetch(req).catch(() => caches.match('/')));
    return;
  }
  e.respondWith(caches.match(req).then((hit) => hit || fetch(req)));
});
`);
    }
  };
}

export default defineConfig({
  plugins: [svelte(), offline()],
  server: { port: 5189, strictPort: true },
  preview: { port: 4189, strictPort: true },
  build: { target: 'es2022', assetsInlineLimit: 0 }
});
